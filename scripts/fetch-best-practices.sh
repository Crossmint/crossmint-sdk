#!/usr/bin/env bash
# Caches every .md file of Paella-Labs/best-practices as one file and prints where it is.
# Uses git, so it works with any GitHub credential git or the gh CLI already has (HTTPS or SSH).
# Refreshes at most once every 24 hours; when GitHub is unreachable it keeps the last good copy.
# Usage: ./scripts/fetch-best-practices.sh [--print]   (--print writes the whole doc to stdout)

REPO="Paella-Labs/best-practices"
CACHE_DIR="${XDG_CACHE_HOME:-$HOME/.cache}/paella-best-practices"
CACHE_FILE="$CACHE_DIR/best-practices.md"
CHECKED_FILE="$CACHE_DIR/checked"
# Written by crossbit-main's .claude/scripts/fetch-best-practices.sh, which also cached every .md file.
LEGACY_FILE="$HOME/.claude/paella-best-practices-cache.md"
LEGACY_SHA_FILE="$HOME/.claude/paella-best-practices-sha.txt"
LEGACY_HEADER="<!-- Generated by .claude/scripts/fetch-best-practices.sh on "
MAX_AGE=86400

export GIT_TERMINAL_PROMPT=0
export GIT_SSH_COMMAND="${GIT_SSH_COMMAND:-ssh -o BatchMode=yes}"
mkdir -p "$CACHE_DIR" 2>/dev/null

valid() {
    [ -f "$1" ] && head -n 1 "$1" | grep -Eq "^<!-- $REPO@[0-9a-f]{40} -->$"
}

fresh() {
    local checked
    valid "$CACHE_FILE" && [ -f "$CHECKED_FILE" ] || return 1
    checked=$(cat "$CHECKED_FILE" 2>/dev/null)
    [[ "$checked" =~ ^[0-9]{1,12}$ ]] || return 1
    [ $(( $(date +%s) - 10#$checked )) -lt "$MAX_AGE" ]
}

fetch() {
    local url
    git init -q --bare "$GIT_DIR_PATH" || return 1
    for attempt in 1 2; do
        for url in "https://github.com/$REPO.git" "git@github.com:$REPO.git"; do
            if git --git-dir="$GIT_DIR_PATH" fetch -q --depth 1 "$url" HEAD 2>/dev/null; then
                return 0
            fi
        done
        if command -v gh >/dev/null 2>&1 && git --git-dir="$GIT_DIR_PATH" -c credential.helper= -c credential.helper='!gh auth git-credential' \
            fetch -q --depth 1 "https://github.com/$REPO.git" HEAD 2>/dev/null; then
            return 0
        fi
        [ "$attempt" = 1 ] && sleep 1
    done
    return 1
}

build() {
    local sha tmp path content found
    sha=$(git --git-dir="$GIT_DIR_PATH" rev-parse FETCH_HEAD) || return 1
    tmp=$(mktemp "$CACHE_DIR/best-practices.md.XXXXXX") || return 1
    if (
        git --git-dir="$GIT_DIR_PATH" ls-tree -rz --name-only "$sha" > "$GIT_DIR_PATH/paths" || exit 1
        echo "<!-- $REPO@$sha -->"
        echo "# Paella/Crossmint best practices"
        echo "Source: https://github.com/$REPO (commit $sha). Follow these when writing or reviewing code, tests, docs, PRs, deployments and operations; cite the file and rule when flagging a violation."
        echo ""
        found=0
        while IFS= read -r -d '' path; do
            case "$path" in *.md) ;; *) continue ;; esac
            found=1
            content=$(git --git-dir="$GIT_DIR_PATH" show "$sha:$path") || exit 1
            echo "## $path"
            echo ""
            printf '%s\n' "$content" | sed -E 's/^(#+)/\1##/'
            echo ""
        done < "$GIT_DIR_PATH/paths"
        [ "$found" = 1 ]
    ) > "$tmp" && mv -f "$tmp" "$CACHE_FILE"; then
        return 0
    fi
    rm -f "$tmp"
    return 1
}

refresh() {
    GIT_DIR_PATH=$(mktemp -d "$CACHE_DIR/repo.XXXXXX" 2>/dev/null) || return 1
    trap 'rm -rf "$GIT_DIR_PATH"' EXIT
    fetch && build || return 1
    { date +%s > "$CHECKED_FILE.$$" && mv -f "$CHECKED_FILE.$$" "$CHECKED_FILE"; } 2>/dev/null || rm -f "$CHECKED_FILE.$$"
    return 0
}

# The old writer rewrote its cache in place and only then recorded the commit, so a sha file at least as new
# as the cache marks a finished write.
legacy_complete() {
    [ -f "$LEGACY_FILE" ] && head -n 1 "$LEGACY_FILE" | grep -qF "$LEGACY_HEADER" || return 1
    grep -Eqx '[0-9a-f]{40}' "$LEGACY_SHA_FILE" 2>/dev/null && ! [ "$LEGACY_SHA_FILE" -ot "$LEGACY_FILE" ]
}

report() {
    local doc="$1" version
    version=$(sed -n "1s|^<!-- $REPO@\([0-9a-f]\{12\}\)[0-9a-f]* -->\$|commit \1|p" "$doc")
    if [ "${2:-}" = "--print" ]; then
        cat "$doc"
        return
    fi
    echo "$REPO (${version:-an earlier snapshot}) is cached at $doc."
    echo "Read that file before writing or reviewing code, and follow it together with this repo's AGENTS.md. Cite the file and rule when flagging a violation in review. It covers:"
    sed -n 's/^## \(.*\.md\)$/- \1/p' "$doc"
}

DOC="$CACHE_FILE"
if ! fresh && ! refresh; then
    if valid "$CACHE_FILE"; then
        echo "fetch-best-practices: could not refresh $REPO; using the copy cached on $(date -r "$CACHE_FILE" '+%Y-%m-%d' 2>/dev/null || echo 'an earlier run')" >&2
    elif legacy_complete; then
        DOC="$LEGACY_FILE"
        echo "fetch-best-practices: could not refresh $REPO; using the older all-files copy at $LEGACY_FILE" >&2
    else
        echo "fetch-best-practices: could not read $REPO with git over HTTPS or SSH and no complete cached copy exists. Ask for read access to $REPO, or check that git can clone it." >&2
        exit 1
    fi
fi
report "$DOC" "${1:-}"
