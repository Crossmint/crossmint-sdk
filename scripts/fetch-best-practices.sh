#!/usr/bin/env bash
# Prints the Paella-Labs/best-practices files listed in its manifest.txt, followed by
# the stack files passed as arguments (e.g. typescript.md). Every manifest entry is required;
# stack files missing upstream are skipped. Without a manifest upstream, every .md file is
# required, as with the previous .claude/scripts fetcher. Results are cached per commit SHA
# and stack list.
# Usage: ./scripts/fetch-best-practices.sh [stack.md ...]

REPO="Paella-Labs/best-practices"
CACHE_DIR="${XDG_CACHE_HOME:-$HOME/.cache}/paella-best-practices"
CACHE_FILE="$CACHE_DIR/best-practices.md"
CHECKED_FILE="$CACHE_DIR/checked"
LEGACY_CACHE_FILE="$HOME/.claude/paella-best-practices-cache.md"
LEGACY_HEADER="<!-- Generated by .claude/scripts/fetch-best-practices.sh"
mkdir -p "$CACHE_DIR"

STACKS="$*"

cached_key() {
    sed -n '1s/^<!-- key: \(.*\) -->$/\1/p' "$CACHE_FILE"
}

cache_matches() {
    [ -f "$CACHE_FILE" ] || return 1
    head -n 1 "$CACHE_FILE" | grep -q '^<!-- key: ' || return 1
    [ "$(cached_key | cut -d' ' -f2-)" = "$STACKS" ]
}

# The previous fetcher cached every .md file of one commit, so its cache holds everything a fetch of
# that commit would return, for any stack list.
legacy_cache_matches() {
    [ -f "$LEGACY_CACHE_FILE" ] || return 1
    head -n 1 "$LEGACY_CACHE_FILE" | grep -qF "$LEGACY_HEADER"
}

serve_cache() {
    if cache_matches; then
        cat "$CACHE_FILE"
        exit 0
    fi
    if legacy_cache_matches; then
        echo "fetch-best-practices: could not refresh from $REPO; serving the previous fetcher's cache at $LEGACY_CACHE_FILE" >&2
        cat "$LEGACY_CACHE_FILE"
        exit 0
    fi
    echo "fetch-best-practices: could not fetch best practices${STACKS:+ with $STACKS} from $REPO and no cached copy for that stack list exists" >&2
    exit 1
}

NOW=$(date +%s)
LAST_CHECKED=0
[ -f "$CHECKED_FILE" ] && LAST_CHECKED=$(cat "$CHECKED_FILE")
case "$LAST_CHECKED" in '' | *[!0-9]*) LAST_CHECKED=0 ;; esac
if [ $((NOW - LAST_CHECKED)) -lt 86400 ] && cache_matches; then
    serve_cache
fi

LATEST_SHA=$(gh api "repos/$REPO/git/ref/heads/main" --jq '.object.sha' 2>/dev/null)
if [ -z "$LATEST_SHA" ]; then
    serve_cache
fi

if cache_matches && [ "$(cached_key)" = "$LATEST_SHA $STACKS" ]; then
    echo "$NOW" > "$CHECKED_FILE"
    serve_cache
fi

TMP_FILE=$(mktemp "$CACHE_DIR/best-practices.XXXXXX") || serve_cache
ERR_FILE="$TMP_FILE.err"
trap 'rm -f "$TMP_FILE" "$ERR_FILE"' EXIT

fetch_file() {
    gh api "repos/$REPO/contents/$1?ref=$LATEST_SHA" -H "Accept: application/vnd.github.raw" 2>"$ERR_FILE"
}

if MANIFEST=$(fetch_file manifest.txt); then
    FILES=$(printf '%s\n' "$MANIFEST" | grep -Ev '^[[:space:]]*(#|$)')
elif grep -q "HTTP 404" "$ERR_FILE"; then
    FILES=$(gh api "repos/$REPO/git/trees/$LATEST_SHA?recursive=1" \
        --jq '.tree[] | select(.type == "blob") | .path | select(endswith(".md"))' 2>"$ERR_FILE") || serve_cache
    [ -n "$FILES" ] || serve_cache
else
    serve_cache
fi

{
    echo "<!-- key: $LATEST_SHA $STACKS -->"
    echo "<!-- Generated by scripts/fetch-best-practices.sh $STACKS on $(date -u '+%Y-%m-%d %H:%M:%S UTC') -->"
    echo ""
    echo "# Paella/Crossmint Best Practices"
    echo "Source: https://github.com/$REPO"
    echo ""
    echo "When generating any content, such as code, documentation, PRs, plans, design documents, or other outputs, ensure it adheres to the following best practices."
    echo ""
} > "$TMP_FILE" || serve_cache

append_file() {
    {
        echo "## $1"
        echo ""
        printf '%s\n' "$2" | sed -E 's/^(#+)/\1##/'
        echo ""
    } >> "$TMP_FILE"
}

FETCHED=" "
while IFS= read -r file; do
    [ -n "$file" ] || continue
    content=$(fetch_file "$file") || serve_cache
    append_file "$file" "$content" || serve_cache
    FETCHED="$FETCHED$file "
done <<< "$FILES"

for file in "$@"; do
    case "$FETCHED" in *" $file "*) continue ;; esac
    if content=$(fetch_file "$file"); then
        append_file "$file" "$content" || serve_cache
    elif ! grep -q "HTTP 404" "$ERR_FILE"; then
        serve_cache
    fi
done

cat "$TMP_FILE"
mv "$TMP_FILE" "$CACHE_FILE" && echo "$NOW" > "$CHECKED_FILE"
